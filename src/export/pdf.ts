/**
 * PDF report — 3 pages, generated client-side with jsPDF.
 *
 * Page 1: title, tank + scenario tables, map figure (captured from the live map canvas).
 * Page 2: depth-class table, exposure table, Q(t) / V(t) charts, mass balance statement.
 * Page 3: assumptions, DEM metadata, run manifest, disclaimer, attribution.
 *
 * All text is vector text (selectable). The only raster is the map figure and the charts.
 */

import { jsPDF } from "jspdf";
import type { DemMetadata, ScenarioSpec, SimulationResult, TankSpec } from "../engine/types";
import type { ExposureResult } from "../engine/exposure";
import { DEPTH_CLASSES, HAZARD_CLASSES } from "../engine/shallowFlow";
import { fmtArea, fmtDepth, fmtLength, fmtRate, fmtTime, fmtVolume, humanDateTime } from "../format";

export interface PdfOptions {
  tank: TankSpec;
  scenario: ScenarioSpec;
  result: SimulationResult;
  exposure: ExposureResult | null;
  dem: DemMetadata | null;
  mapImage: string | null; // data URL
  attribution: string;
  runHash: string;
  appVersion: string;
  scenarioLabel: string;
}

const MM = { w: 210, h: 297, margin: 14 };

export async function buildPdf(o: PdfOptions): Promise<Blob> {
  const doc = new jsPDF({ unit: "mm", format: "a4", orientation: "portrait" });
  const { tank, result, dem } = o;
  let y = 0;

  const header = (title: string, subtitle: string) => {
    doc.setFillColor(11, 18, 32);
    doc.rect(0, 0, MM.w, 24, "F");
    doc.setTextColor(230, 237, 247);
    doc.setFontSize(15);
    doc.setFont("helvetica", "bold");
    doc.text(title, MM.margin, 12);
    doc.setFontSize(8.5);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(147, 164, 189);
    doc.text(subtitle, MM.margin, 18.5);
    doc.setTextColor(239, 68, 68);
    doc.setFontSize(7.5);
    doc.text("SCREENING TOOL — NOT A DESIGN-GRADE DAM-BREAK STUDY", MM.w - MM.margin, 18.5, { align: "right" });
    doc.setTextColor(30, 30, 30);
    y = 30;
  };

  const footer = (page: number, total: number) => {
    doc.setFontSize(7);
    doc.setTextColor(120, 130, 145);
    doc.text(
      `Generated by TankBreach v${o.appVersion} · run ${o.runHash} · ${humanDateTime()}`,
      MM.margin,
      MM.h - 7,
    );
    doc.text(`Page ${page} of ${total}`, MM.w - MM.margin, MM.h - 7, { align: "right" });
    doc.setTextColor(30, 30, 30);
  };

  const sectionTitle = (t: string) => {
    doc.setFontSize(10.5);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(14, 100, 150);
    doc.text(t, MM.margin, y);
    doc.setDrawColor(180, 200, 220);
    doc.line(MM.margin, y + 1.2, MM.w - MM.margin, y + 1.2);
    doc.setTextColor(30, 30, 30);
    y += 5.5;
  };

  const table = (rows: [string, string][], colWidth = 62) => {
    doc.setFontSize(8.5);
    for (const [k, v] of rows) {
      doc.setFont("helvetica", "normal");
      doc.setTextColor(90, 100, 115);
      doc.text(k, MM.margin, y);
      doc.setFont("helvetica", "bold");
      doc.setTextColor(25, 30, 40);
      const lines = doc.splitTextToSize(v, MM.w - MM.margin * 2 - colWidth);
      doc.text(lines, MM.margin + colWidth, y);
      y += Math.max(4.6, lines.length * 4.2);
    }
    y += 2;
  };

  // ------------------------------------------------------------------ page 1
  header(
    "MUNICIPAL FLOOD INUNDATION STUDY",
    `${tank.name} · ${o.scenarioLabel} · ${tank.location.lat.toFixed(5)}°N, ${tank.location.lng.toFixed(5)}°E`,
  );

  sectionTitle("Tank specification");
  table([
    ["Tank name", tank.name],
    ["Shape", tank.shape.replace(/_/g, " ")],
    [
      "Dimensions",
      tank.shape === "rectangular"
        ? `${tank.lengthM ?? "?"} × ${tank.widthM ?? "?"} m, wall ${tank.wallHeightM} m`
        : `Ø ${tank.diameterM ?? "?"} m, wall ${tank.wallHeightM} m`,
    ],
    ["Water level at release", `${tank.waterHeadM.toFixed(2)} m above the tank floor`],
    ["Tank floor elevation", `${tank.baseElevationM.toFixed(2)} m (vertical datum: DEM)`],
    ["Location (WGS84)", `${tank.location.lat.toFixed(6)} N, ${tank.location.lng.toFixed(6)} E`],
    ["Fluid", tank.fluid],
  ]);

  sectionTitle("Scenario");
  table([
    ["Mode", o.scenario.mode.replace(/_/g, " ")],
    o.scenario.mode === "leak"
      ? [
          "Opening",
          o.scenario.holeShape === "circular"
            ? `circular, Ø ${((o.scenario.holeDiameterM ?? 0) * 1000).toFixed(0)} mm at ${o.scenario.holeElevationAboveBaseM} m above the floor, Cd ${o.scenario.dischargeCoefficientCd}`
            : `rectangular ${o.scenario.holeWidthM} × ${o.scenario.holeHeightM} m at ${o.scenario.holeElevationAboveBaseM} m, Cd ${o.scenario.dischargeCoefficientCd}`,
        ]
      : ["Breach", `width ${o.scenario.breachWidthM} m, development ${o.scenario.breachDevelopmentSeconds ?? 0} s`],
    ["Volume released", fmtVolume(result.mass.releasedM3)],
    ["Peak discharge", fmtRate(result.hydro.peakQ)],
    [result.hydro.stopReason === "empty" ? "Time to empty" : "Release duration", fmtTime(result.hydro.emptyTimeS)],
    ["Simulation end", fmtTime(result.frameTimes[result.frameTimes.length - 1] ?? 0)],
  ]);

  sectionTitle("Modelled inundation — key results");
  const affectedHa = result.stats.affectedAreaM2 / 10000;
  table(
    [
      ["Inundated footprint", `${affectedHa.toFixed(2)} ha (${fmtArea(result.stats.affectedAreaM2)})`],
      ["Maximum modelled depth", fmtDepth(result.stats.maxDepthM)],
      ["Mean depth over wet footprint", fmtDepth(result.stats.meanDepthAffectedM)],
      ["Elevation DEM source", dem ? `${dem.label} (${dem.gridCellSizeM.toFixed(0)} m)` : "Copernicus GLO-30 DSM (30 m)"],
      ["Peak velocity", `${result.stats.maxVelocityMs.toFixed(2)} m/s`],
      ["Maximum extent from the tank", fmtLength(result.stats.maxExtentDistanceM)],
      ["Mass balance closing error", `${result.mass.errorPercent.toFixed(2)} % ${result.mass.ok ? "(within tolerance)" : "(OUT OF TOLERANCE)"}`],
    ],
    78,
  );

  if (o.mapImage) {
    const imgW = MM.w - MM.margin * 2;
    const imgH = Math.min(92, imgW * 0.62);
    try {
      doc.addImage(o.mapImage, "JPEG", MM.margin, y, imgW, imgH);
      doc.setDrawColor(160, 175, 195);
      doc.rect(MM.margin, y, imgW, imgH);
      y += imgH + 3;
      doc.setFontSize(7);
      doc.setTextColor(110, 120, 135);
      doc.text(
        `Map figure captured at export time. ${dem ? `${dem.label}, cell ${dem.gridCellSizeM.toFixed(0)} m.` : ""}`,
        MM.margin,
        y,
      );
      y += 3.5;
      doc.setTextColor(30, 30, 30);
    } catch {
      doc.setFontSize(8);
      doc.text("(map figure could not be captured)", MM.margin, y + 6);
      y += 12;
    }
  }

  footer(1, 3);

  // ------------------------------------------------------------------ page 2
  doc.addPage();
  header("Impact assessment", `${tank.name} · ${o.scenarioLabel}`);

  sectionTitle("Depth classes");
  doc.setFontSize(8.5);
  doc.setFont("helvetica", "bold");
  doc.text("Class", MM.margin, y);
  doc.text("Area (ha)", MM.margin + 60, y, { align: "right" });
  doc.text("Share", MM.margin + 88, y, { align: "right" });
  doc.text("Cells", MM.margin + 118, y, { align: "right" });
  y += 4;
  doc.setFont("helvetica", "normal");
  const totalArea = Math.max(1, result.stats.affectedAreaM2);
  for (const c of result.classes) {
    if (c.areaM2 <= 0) continue;
    doc.setTextColor(30, 30, 30);
    doc.text(c.label, MM.margin, y);
    doc.text((c.areaM2 / 10000).toFixed(2), MM.margin + 60, y, { align: "right" });
    doc.text(`${((c.areaM2 / totalArea) * 100).toFixed(1)} %`, MM.margin + 88, y, { align: "right" });
    doc.text(String(c.cellCount), MM.margin + 118, y, { align: "right" });
    y += 4.4;
  }
  y += 4;

  sectionTitle("Hazard to people (depth × velocity)");
  doc.setFontSize(8);
  doc.setTextColor(90, 100, 115);
  for (const h of HAZARD_CLASSES.slice(1)) {
    doc.text(`• ${h.label} — ${h.note}`, MM.margin, y);
    y += 4.2;
  }
  doc.setTextColor(30, 30, 30);
  y += 3;

  sectionTitle("Exposure (OpenStreetMap assets)");
  if (o.exposure) {
    table(
      [
        ["Buildings exposed to modelled flooding", String(o.exposure.totals.buildingCount)],
        ["— with ≥ 0.3 m modelled depth", String(o.exposure.buildings.filter((b) => b.maxDepthM >= 0.3).length)],
        ["— with ≥ 1.0 m modelled depth", String(o.exposure.buildings.filter((b) => b.maxDepthM >= 1).length)],
        ["Road length exposed", fmtLength(o.exposure.totals.roadAffectedM)],
        [
          "Road length by class",
          Object.entries(o.exposure.totals.roadByClass)
            .map(([k, v]) => `${k}: ${fmtLength(v)}`)
            .join(", ") || "—",
        ],
      ],
      78,
    );
    doc.setFontSize(7);
    doc.setTextColor(140, 90, 30);
    const note = doc.splitTextToSize(o.exposure.notes.join(" "), MM.w - MM.margin * 2);
    doc.text(note, MM.margin, y);
    y += note.length * 3.2 + 3;
    doc.setTextColor(30, 30, 30);
  } else {
    doc.setFontSize(8.5);
    doc.text("Exposure was not assessed for this run (no OSM data requested).", MM.margin, y);
    y += 6;
  }

  // ---- charts as small SVG-free vector plots
  sectionTitle("Release hydrograph and stored volume");
  drawChart(doc, MM.margin, y, MM.w - MM.margin * 2, 34, result.hydro.points.map((p) => ({ x: p.t, y: p.q })), "Q (m³/s)", "#0284c7");
  y += 38;
  drawChart(
    doc,
    MM.margin,
    y,
    MM.w - MM.margin * 2,
    30,
    result.hydro.points.map((p) => ({ x: p.t, y: p.vRemaining })),
    "Volume in tank (m³)",
    "#0f766e",
  );
  y += 36;

  sectionTitle("Mass balance");
  table(
    [
      ["Released by the tank", fmtVolume(result.mass.releasedM3)],
      ["Stored on the terrain at the end", fmtVolume(result.mass.wetM3)],
      ["Boundary outflow", fmtVolume(result.mass.outflowM3)],
      ["Infiltrated / abstracted", fmtVolume(result.mass.infiltrationM3)],
      ["Left in the tank", fmtVolume(result.mass.tankResidualM3)],
      ["Closing error", `${result.mass.errorM3.toFixed(3)} m³ (${result.mass.errorPercent.toFixed(2)} %)`],
    ],
    78,
  );
  footer(2, 3);

  // ------------------------------------------------------------------ page 3
  doc.addPage();
  header("Assumptions, data provenance and limits", `${tank.name} · run ${o.runHash}`);

  sectionTitle("Terrain data");
  table(
    [
      ["DEM source", dem?.label ?? "not recorded"],
      ["Native resolution", dem ? `${dem.resolutionM} m` : "—"],
      ["Analysis cell size", dem ? `${dem.gridCellSizeM.toFixed(0)} m` : "—"],
      ["Vertical accuracy", dem?.verticalAccuracyM !== null && dem ? `±${dem.verticalAccuracyM} m (LE90, stated)` : "not stated"],
      ["Surface model", dem?.surfaceModel ? "DSM — includes buildings and vegetation" : "DTM or unknown"],
      ["Licence", dem?.licence ?? "—"],
      ["Attribution", dem?.attribution ?? "—"],
    ],
    40,
  );

  sectionTitle("Model assumptions");
  doc.setFontSize(8);
  const assumptions = [
    "Release: orifice law Q = Cd·A·√(2gh) with falling head; broad-crested weir Q = 1.7·b·H^1.5 for breach/overtopping.",
    `Flow: 2-D shallow-water equations in inertial form (Bates, Horritt & Fewtrell 2010), explicit, CFL-controlled, Manning n = ${result.options.manningN}.`,
    `Grid: ${result.grid.nx} × ${result.grid.ny} cells at ${result.grid.dx.toFixed(0)} m in a local azimuthal projection centred on the tank.`,
    "All four domain edges are open outfalls; water leaving the domain is reported as boundary outflow and is not deleted.",
    `Infiltration/surface loss: ${result.options.infiltrationMmPerHr} mm/hr, applied only to wet cells.`,
    `Reporting threshold: ${result.options.reportingDepthM} m depth.`,
  ];
  for (const a of assumptions) {
    const lines = doc.splitTextToSize(`• ${a}`, MM.w - MM.margin * 2);
    doc.text(lines, MM.margin, y);
    y += lines.length * 3.6 + 1.2;
  }
  y += 2;

  sectionTitle("Known limitations — read before using these numbers");
  doc.setTextColor(150, 30, 30);
  const limits = [
    "No advection/momentum transport: surge fronts, hydraulic jumps and impact pressures are not represented.",
    "The release is applied as a surface inflow over the tank footprint; the vertical jet and impact cratering are not modelled.",
    "No storm-drain network, culverts, kerbs, walls or building blockage of flow.",
    "No sediment transport, erosion, or soil infiltration physics.",
    "DEM vertical error (often ±2–4 m for global 30 m data) is not propagated into the depth rasters; absolute depths carry that uncertainty.",
    "Buildings and roads are sampled from the modelled raster, not clipped against it; exposure is indicative, not a damage assessment.",
    "This is a screening and awareness tool. It is not a regulatory or design-grade study, and it does not replace HEC-RAS, TUFLOW, ANUGA or a site-specific survey.",
  ];
  doc.setFontSize(8);
  for (const l of limits) {
    const lines = doc.splitTextToSize(`• ${l}`, MM.w - MM.margin * 2);
    doc.text(lines, MM.margin, y);
    y += lines.length * 3.6 + 1.2;
  }
  doc.setTextColor(30, 30, 30);
  y += 2;

  sectionTitle("Run manifest (for reproducibility)");
  const manifest = {
    app: `TankBreach v${o.appVersion}`,
    runHash: o.runHash,
    generatedUtc: new Date().toISOString(),
    tank,
    scenario: o.scenario,
    simulationOptions: result.options,
    dem: dem ?? null,
    results: {
      releasedM3: result.mass.releasedM3,
      affectedAreaM2: result.stats.affectedAreaM2,
      maxDepthM: result.stats.maxDepthM,
      maxExtentDistanceM: result.stats.maxExtentDistanceM,
      peakDischargeM3s: result.hydro.peakQ,
      emptyTimeS: result.hydro.emptyTimeS,
      massBalance: result.mass,
    },
  };
  doc.setFont("courier", "normal");
  doc.setFontSize(6.2);
  const mtext = doc.splitTextToSize(JSON.stringify(manifest, null, 1), MM.w - MM.margin * 2);
  const usable = MM.h - y - 18;
  const maxLines = Math.floor(usable / 2.6);
  doc.text(mtext.slice(0, maxLines), MM.margin, y);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(7);
  doc.setTextColor(110, 120, 135);
  doc.text(doc.splitTextToSize(o.attribution, MM.w - MM.margin * 2), MM.margin, MM.h - 14);

  footer(3, 3);
  return doc.output("blob");
}

function drawChart(
  doc: jsPDF,
  x: number,
  y: number,
  w: number,
  h: number,
  series: { x: number; y: number }[],
  label: string,
  colour: string,
) {
  if (series.length === 0) return;
  const x0 = Math.min(...series.map((p) => p.x));
  const x1 = Math.max(...series.map((p) => p.x), x0 + 1);
  const y1 = Math.max(...series.map((p) => p.y), 1e-9);
  doc.setDrawColor(200, 210, 225);
  doc.setFillColor(250, 252, 255);
  doc.rect(x, y, w, h, "FD");
  doc.setDrawColor(colour);
  doc.setLineWidth(0.5);
  let prev: { x: number; y: number } | null = null;
  for (const p of series) {
    const px = x + ((p.x - x0) / (x1 - x0)) * w;
    const py = y + h - (p.y / y1) * h;
    if (prev) doc.line(prev.x, prev.y, px, py);
    prev = { x: px, y: py };
  }
  doc.setFontSize(6.5);
  doc.setTextColor(90, 100, 115);
  doc.text(label, x + 1.5, y + 3.5);
  doc.text(`${y1.toPrecision(3)}`, x + w - 1, y + 3.5, { align: "right" });
  doc.text(`${fmtTime(x1)}`, x + w - 1, y + h - 1, { align: "right" });
  doc.text("0", x + 1.5, y + h - 1);
  doc.setLineWidth(0.2);
  doc.setTextColor(30, 30, 30);
}

// ---------------------------------------------------------------- comparison report
export interface ComparePdfOptions {
  tank: TankSpec;
  dem: DemMetadata | null;
  runs: { label: string; result: SimulationResult }[];
}

/**
 * Multi-scenario comparison report: one summary table of every run plus a map of each
 * scenario's depth footprint row. Page 1 carries the table, the disclaimer and the DEM
 * provenance; a footer on every page carries the scenario hashes.
 */
export async function buildComparePdf(o: ComparePdfOptions): Promise<Blob> {
  const doc = new jsPDF({ unit: "mm", format: "a4", orientation: "portrait" });
  const M = 14;
  const W = 210;
  const runs = o.runs;
  let y = 0;

  doc.setFillColor(11, 18, 32);
  doc.rect(0, 0, W, 24, "F");
  doc.setTextColor(230, 237, 247);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(15);
  doc.text("MUNICIPAL SCENARIO COMPARISON (CASE 1 vs CASE 2)", M, 12);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8.5);
  doc.setTextColor(147, 164, 189);
  doc.text(`${o.tank.name} · ${humanDateTime()} · Focus Area: 1.0 km²`, M, 19);
  y = 30;

  doc.setTextColor(20, 25, 35);
  doc.setFontSize(10);
  doc.setFont("helvetica", "bold");
  doc.text("Comparative Results in 1.0 km² Domain", M, y);
  y += 5;

  const cols = ["Metric", ...runs.map((r) => r.label)];
  const rows: string[][] = [
    ["Released volume", ...runs.map((r) => fmtVolume(r.result.mass.releasedM3))],
    ["Peak discharge", ...runs.map((r) => fmtRate(r.result.hydro.peakQ))],
    ["Affected area", ...runs.map((r) => fmtArea(r.result.stats.affectedAreaM2))],
    [
      "Inundated in 1.0 km²",
      ...runs.map(
        (r) =>
          `${(r.result.stats.affectedAreaM2 / 10000).toFixed(2)} ha (${((r.result.stats.affectedAreaM2 / 1e6) * 100).toFixed(1)}%)`,
      ),
    ],
    ["Max depth", ...runs.map((r) => fmtDepth(r.result.stats.maxDepthM))],
    ["Peak velocity", ...runs.map((r) => `${r.result.stats.maxVelocityMs.toFixed(2)} m/s`)],
    ["Flow direction", ...runs.map((r) => `${r.result.flow.dominantLabel} (${r.result.flow.dominantDirDeg.toFixed(0)}°)`)],
    ["Max extent", ...runs.map((r) => fmtLength(r.result.stats.maxExtentDistanceM))],
    [
      "Municipal response",
      ...runs.map((r) =>
        r.result.hydro.method === "orifice" ? "Valve isolation / pump diversion" : "Immediate siren / evacuation",
      ),
    ],
    ["Mass balance error", ...runs.map((r) => `${r.result.mass.errorPercent.toFixed(2)} %`)],
    ["Run hash", ...runs.map((r) => r.result.hash)],
  ];

  const colW = (W - 2 * M) / cols.length;
  doc.setFontSize(8);
  doc.setFont("helvetica", "bold");
  cols.forEach((c, i) => {
    doc.text(doc.splitTextToSize(c, colW - 2), M + i * colW, y);
  });
  y += 6;
  doc.setFont("helvetica", "normal");
  for (const row of rows) {
    row.forEach((cell, i) => {
      const lines = doc.splitTextToSize(cell, colW - 2) as string[];
      doc.text(lines, M + i * colW, y);
    });
    doc.setDrawColor(225, 230, 238);
    doc.line(M, y + 1.4, W - M, y + 1.4);
    y += 6;
  }

  y += 4;
  doc.setFontSize(8);
  doc.setTextColor(120, 60, 20);
  const disc = doc.splitTextToSize(
    "SCREENING TOOL — not a design-grade dam-break study. Results depend on open DEM accuracy (typically ±2–4 m vertical) and on simplified hydraulics. A licensed hydraulic engineer and a field survey must confirm any real-world conclusion. No area is labelled safe or unsafe by this tool.",
    W - 2 * M,
  ) as string[];
  doc.text(disc, M, y);
  y += disc.length * 4 + 4;

  doc.setTextColor(30, 35, 45);
  doc.setFontSize(8);
  doc.text(`Tank: ${o.tank.name} · ${o.tank.shape} · ${o.tank.capacityM3} m³ · water level ${o.tank.waterHeadM} m`, M, y);
  y += 4;
  doc.text(`Elevation: ${o.dem?.label ?? "unknown"} (${o.dem?.resolutionM ?? "?"} m, ${o.dem?.surfaceModel ? "surface model (DSM)" : "terrain model"})`, M, y);

  // Map row: each scenario's depth footprint at the same scale.
  const perPage = runs.length <= 2 ? 2 : runs.length;
  for (let i = 0; i < runs.length; i += perPage) {
    doc.addPage();
    let yy = 20;
    doc.setFontSize(11);
    doc.setTextColor(20, 25, 35);
    doc.text("Depth footprint by scenario", M, 14);
    for (const run of runs.slice(i, i + perPage)) {
      const boxW = W - 2 * M;
      const boxH = 60;
      const png = rasterToPdfPng(run.result);
      if (png) {
        try {
          doc.addImage(png, "PNG", M, yy, boxW, boxH, undefined, "FAST");
        } catch {
          /* jsPDF can reject an odd PNG; the label below still identifies the run */
        }
      }
      doc.setFontSize(9);
      doc.setTextColor(30, 35, 45);
      doc.text(
        `${run.label} — ${fmtArea(run.result.stats.affectedAreaM2)}, max ${fmtDepth(run.result.stats.maxDepthM)}, peak ${fmtRate(run.result.hydro.peakQ)}`,
        M,
        yy + boxH + 5,
      );
      yy += boxH + 12;
    }
  }

  const pages = doc.getNumberOfPages();
  for (let p = 1; p <= pages; p++) {
    doc.setPage(p);
    doc.setFontSize(7);
    doc.setTextColor(120, 130, 145);
    doc.text(`TankBreach · screening comparison · page ${p} of ${pages}`, M, 290);
    doc.text(runs.map((r) => r.result.hash).join(" / "), W - M, 290, { align: "right" });
  }

  return doc.output("blob");
}

/** Renders a result's depth footprint into a data URL for embedding in the PDF. */
function rasterToPdfPng(result: SimulationResult): string | null {
  if (typeof document === "undefined") return null;
  const { nx, ny } = result.grid;
  const cv = document.createElement("canvas");
  cv.width = nx;
  cv.height = ny;
  const ctx = cv.getContext("2d");
  if (!ctx) return null;
  const img = ctx.createImageData(nx, ny);
  for (let r = 0; r < ny; r++) {
    const gr = ny - 1 - r;
    for (let c = 0; c < nx; c++) {
      const d = result.maxDepth[gr * nx + c];
      const o = (r * nx + c) * 4;
      if (!(d >= 0.005)) {
        img.data[o + 3] = 0;
        continue;
      }
      const cls = DEPTH_CLASSES.findIndex((k) => d >= k.minM && (k.maxM === null || d < k.maxM));
      const colour = DEPTH_CLASSES[Math.max(0, cls)].colour;
      img.data[o] = parseInt(colour.slice(1, 3), 16);
      img.data[o + 1] = parseInt(colour.slice(3, 5), 16);
      img.data[o + 2] = parseInt(colour.slice(5, 7), 16);
      img.data[o + 3] = 220;
    }
  }
  ctx.putImageData(img, 0, 0);
  return cv.toDataURL("image/png");
}
